import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const projectRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const LANGUAGES = ['en', 'ku', 'kmr', 'ar', 'fr', 'tr', 'sv'];

export async function localizedCopySource(root = projectRoot) {
  const html = await readFile(path.join(root, 'preview_site/index.html'), 'utf8');
  const keys = [...new Set([...html.matchAll(/\bdata-i18n(?:-ph|-aria|-opt)?="([^"]+)"/g)]
    .map((match) => match[1]))].sort();
  // Execute only the repository's authored dictionaries at build time. Calling
  // their real merger keeps server text identical to a fully loaded browser,
  // including identity-copy overrides, UI labels and English fallback strings.
  const context = vm.createContext({
    window: {},
    document: { documentElement: { dataset: {} }, querySelectorAll() { return []; } },
    localStorage: { setItem() {} }
  });
  for (const file of ['i18n.js', 'i18n-more.js']) {
    const source = await readFile(path.join(root, 'preview_site/js', file), 'utf8');
    vm.runInContext(source, context, { filename: file, timeout: 1_000 });
  }
  context.window.__i18nMoreLoaded = true;
  const dictionaries = {};
  for (const lang of LANGUAGES) {
    context.window.applyLang(lang);
    const dict = context.window.BQ_DICT;
    dictionaries[lang] = Object.fromEntries(keys
      .filter((key) => typeof dict[key] === 'string')
      .map((key) => [key, dict[key]]));
  }
  return '// Generated by scripts/generate-localized-copy.mjs; edit the browser dictionaries.\n'
    + 'export const LOCALIZED_COPY = ' + JSON.stringify(dictionaries, null, 2) + ';\n';
}

export async function generateLocalizedCopy(root = projectRoot) {
  const output = path.join(root, 'functions/_localized-copy.js');
  const source = await localizedCopySource(root);
  let previous;
  try { previous = await readFile(output, 'utf8'); } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (source === previous) return false;
  await writeFile(output, source);
  return true;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) await generateLocalizedCopy();
