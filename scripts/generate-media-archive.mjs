const CARD_SIZES = '(max-width: 600px) calc(100vw - 32px), (max-width: 619px) calc(100vw - 64px), (max-width: 999px) calc((100vw - 88px) / 2), (max-width: 1303px) calc((100vw - 112px) / 3), 397px';

/* Existing thumbnails remain srcset candidates next to the original, letting
   the browser choose a suitable file for each viewport and pixel density.
   src stays the original for crawlers and browsers without srcset support. */
function srcset(owner, source, thumbs) {
  const thumb = thumbs.get(owner.path);
  if (!thumb || thumb.width >= owner.width) return '';
  return ` srcset="${escape(thumb.url)} ${thumb.width}w, ${escape(source)} ${owner.width}w" sizes="${CARD_SIZES}"`;
}

function card(item, index, label, thumbs) {
  const owner = item.canonical || item;
  const href = workPath(owner.coll, owner.index);
  const source = item.type === 'image' ? mediaPath(owner.path) : item.poster;
  const title = displayTitle(item.coll, item.index);
  const set = item.type === 'image' ? srcset(owner, source, thumbs) : '';
  const image = source ? `<a class="media" href="${escape(href)}" tabindex="-1" aria-hidden="true"><img src="${escape(source)}"${set} alt="${escape(describe(owner).alt)}" width="${owner.width}" height="${owner.height}" loading="${index < 2 ? 'eager' : 'lazy'}" decoding="async">${item.type === 'video' ? '<span class="play-badge">Play film ↗</span>' : ''}</a>` : '';
  return `<article class="card" id="work-${item.coll}-${item.index}">${image}<div class="caption"><p class="work-number">${String(item.index).padStart(3, '0')} / ${item.type === 'video' ? 'Film' : 'Image'}</p><h2><a href="${escape(href)}">${escape(title)}${item.type === 'video' ? ' · Watch' : ''}<span aria-hidden="true"> ↗</span></a></h2><p class="work-type">${escape(label)}</p></div></article>`;
}

function categoryCard(coll, slug, label, collection, number, thumbs) {
  const item = collection[0].canonical || collection[0];
  const source = item.type === 'image' ? mediaPath(item.path) : item.poster;
  const set = item.type === 'image' ? srcset(item, source, thumbs) : '';
  // The entire tile has one accessible link; its image is a decorative preview
  // of a collection whose name and size immediately follow it.
  const preview = source ? `<img src="${escape(source)}"${set} alt="" width="${item.width}" height="${item.height}" loading="${number <= 3 ? 'eager' : 'lazy'}" decoding="async">` : '<span class="preview-empty" aria-hidden="true">↗</span>';
  return `<a class="category-card" href="${pageURL(slug)}"><div class="category-cover" data-discipline="${coll}">${preview}${coll === 'video' ? '<span class="play-badge" aria-hidden="true">Films &amp; motion ↗</span>' : ''}</div><div class="category-meta"><span class="category-number">${String(number).padStart(2, '0')}</span><div><h3>${escape(label)}</h3><p>${escape(DISCIPLINES[coll])}</p></div><span class="category-arrow" aria-hidden="true">↗</span></div><span class="category-count">${collection.length} ${coll === 'video' ? 'films' : 'images'}</span></a>`;
}

function collectionNavigation(collections, active) {
  return `<nav class="collection-nav" aria-label="Collections"><a href="/archive/">All collections</a>${Object.entries(ARCHIVES).filter(([coll]) => collections[coll].length).map(([coll, [slug, label]]) => `<a href="${pageURL(slug)}"${coll === active ? ' class="is-active" aria-current="true"' : ''}>${escape(label)}<span>${collections[coll].length}</span></a>`).join('')}</nav>`;
}

export function buildMediaArchive(manifest, { pageSize = 24, thumbs = new Map(), fontFaces = '', motionScript } = {}) {
  if (!Number.isInteger(pageSize) || pageSize < 1 || pageSize > 100) throw new Error('Invalid archive page size');
  const catalog = catalogFromManifest(manifest);
  // The upstream catalogue owns indexing, media URLs and duplicate detection.
  // Do not silently drop an invalid manifest entry from the complete archive.
  if (catalog.byPath.size !== manifest.images.length + manifest.videos.length) throw new Error('Invalid or duplicate archive media');
  for (const coll of Object.keys(COLLECTIONS)) if (!ARCHIVES[coll]) throw new Error(`Collection missing from archive: ${coll}`);
  const canonicalItems = [...catalog.byPath.values()].filter(item => !item.canonical);
  const imageCount = canonicalItems.filter(item => item.type === 'image').length;
  const videoCount = canonicalItems.filter(item => item.type === 'video').length;
  // A work may belong to several disciplines, but must appear only once in
  // each collection. Keep the first entry and its original stable index;
  // the shared catalogue still owns every alias and its canonical redirect.
  const collections = Object.fromEntries(Object.entries(catalog.byColl).map(([coll, items]) => {
    const seen = new Set();
    return [coll, items.filter(item => {
      const owner = item.canonical || item;
      if (seen.has(owner.path)) return false;
      seen.add(owner.path);
      return true;
    })];
  }));
  const files = new Map(), pages = [], categories = [];
  if (motionScript) files.set(motionScript.path, motionScript.body);
  const addPage = (route, values) => {
    files.set(`${route.slice(1)}index.html`, documentHTML({ ...values, route, fontFaces, motionScript }));
    pages.push(route);
  };
  for (const [coll, [slug, label]] of Object.entries(ARCHIVES)) {
    // Preserve manifest indexes: /design/<coll>/<index> uses this same order.
    const collection = collections[coll];
    if (!collection.length) continue;
    categories.push(categoryCard(coll, slug, label, collection, categories.length + 1, thumbs));
    const totalPages = Math.ceil(collection.length / pageSize);
    for (let page = 1; page <= totalPages; page++) {
      const batch = collection.slice((page - 1) * pageSize, page * pageSize);
      const route = pageURL(slug, page);
      const title = `${label} — Archive${totalPages > 1 ? `, page ${page}` : ''}`;
      const range = `${(page - 1) * pageSize + 1}–${Math.min(page * pageSize, collection.length)}`;
      const description = `${label} from Barakat Qurtas’s portfolio. Browse works ${range} of ${collection.length}.`;
      const navigation = pagination(slug, page, totalPages);
      const first = batch[0].canonical || batch[0];
      addPage(route, { title, description, image: first.type === 'image' ? mediaUrl(first.path) : first.poster ? SITE + first.poster : null,
        content: `<nav class="crumb" aria-label="Breadcrumb"><a href="/archive/">Archive</a><span aria-hidden="true">/</span><span>${escape(label)}</span></nav><section class="intro collection-intro"><div class="intro-title"><p class="eyebrow">The archive / ${String(Object.keys(ARCHIVES).indexOf(coll) + 1).padStart(2, '0')}</p><h1>${escape(label)}</h1></div><div class="intro-copy"><p>${escape(DISCIPLINES[coll])}. ${coll === 'video' ? 'Films and motion, from the first frame to the final cut. Choose a film to watch.' : 'A closer look at the work. Select an image to see the original artwork and its details.'}</p><p class="collection-total">${collection.length} ${coll === 'video' ? 'films' : 'images'} in this collection</p></div></section>${collectionNavigation(collections, coll)}<div class="results-bar"><p>Showing ${range} <span>of ${collection.length} ${coll === 'video' ? 'films' : 'images'}</span></p><a class="text-link" href="/archive/">All collections <span aria-hidden="true">↗</span></a></div>${navigation}<div class="work-grid">${batch.map((item, index) => card(item, index, label, thumbs)).join('\n')}</div>${navigation}` });
    }
  }
  addPage('/archive/', { title: 'Work Archive', description: `Browse ${imageCount} unique images and ${videoCount} videos from Barakat Qurtas’s design portfolio.`,
    image: manifest.images.length ? mediaUrl(manifest.images[0].path) : null,
    content: `<section class="intro archive-intro"><div class="intro-title"><p class="eyebrow"><span class="status-dot" aria-hidden="true"></span> Independent practice · Hewlêr</p><h1>A living <span>archive.</span></h1></div><div class="intro-copy"><p>A collection of ideas made real. Identity, print, images and motion — different forms, one connected creative practice.</p><a class="text-link" href="#collections">Explore the collections <span aria-hidden="true">↓</span></a></div></section><dl class="archive-stats"><div><dt>Unique images</dt><dd>${imageCount}</dd></div><div><dt>Films &amp; motion</dt><dd>${videoCount}</dd></div><div><dt>Collections</dt><dd>${categories.length}</dd></div></dl><section id="collections" class="collections"><div class="section-heading"><h2>Explore by discipline.</h2><p>01—${String(categories.length).padStart(2, '0')} / Select a collection</p></div><div class="category-grid">${categories.join('\n')}</div></section>` });
  files.set('sitemap-gallery.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${pages.map(route => `  <url><loc>${SITE}${route}</loc></url>`).join('\n')}\n</urlset>\n`);
  const routeModule = `// Generated by scripts/generate-media-archive.mjs; do not edit.\nexport const MEDIA_ARCHIVE_ROUTES = new Set(${JSON.stringify([...pages].sort(), null, 2)});\n`;
  return { files, pages, routeModule, imageCount, videoCount };
}

function webpWidth(bytes) {
  if (bytes.toString('latin1', 0, 4) !== 'RIFF' || bytes.toString('latin1', 8, 12) !== 'WEBP') return 0;
  const chunk = bytes.toString('latin1', 12, 16);
  if (chunk === 'VP8 ') return bytes.readUInt16LE(26) & 0x3fff;
  if (chunk === 'VP8L') return (bytes.readUInt32LE(21) & 0x3fff) + 1;
  if (chunk === 'VP8X') return bytes.readUIntLE(24, 3) + 1;
  return 0;
}

/* Inputs the archive takes from the built site: the gallery thumbnails that
   exist (with their real widths) and the Manrope faces from fonts.css. The
   faces keep only src + unicode-range, so the archive renders as before. */
export async function archiveAssets(siteRoot = path.join(projectRoot, 'preview_site'), analyticsClient = ANALYTICS_CLIENT_JS) {
  const thumbs = new Map();
  const base = path.join(siteRoot, 'assets/thumbs');
  let folders = [];
  try { folders = await readdir(base); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  for (const folder of folders) {
    let files = [];
    try { files = await readdir(path.join(base, folder)); } catch { continue; }
    for (const file of files.filter((name) => name.endsWith('.webp'))) {
      const handle = await readFile(path.join(base, folder, file));
      const width = webpWidth(handle);
      if (width) thumbs.set(`${folder}/${file}`, { url: `/assets/thumbs/${folder}/${encodeURIComponent(file)}`, width });
    }
  }
  const css = await readFile(path.join(siteRoot, 'css/fonts.css'), 'utf8');
  const fontFaces = [...css.matchAll(/@font-face \{[^}]*font-family: 'Manrope';[^}]*\}/g)].map(([face]) => {
    const src = face.match(/src: (url\([^)]+\) format\('woff2'\))/)[1];
    const range = face.match(/unicode-range: ([^;]+);/)[1];
    return `@font-face{font-family:Manrope;src:${src};font-display:swap;unicode-range:${range}}`;
  }).join('\n');
  if (!fontFaces) throw new Error('Manrope faces not found in fonts.css');
  // A content-named file cannot reuse stale bytes from a previous deployment.
  // Compile from the authored source, also when generating a test site root.
  const source = await readFile(path.join(projectRoot, 'preview_site/js/archive.js'), 'utf8');
  const compiled = await minify(`${source}\n${BACK_TO_TOP_JS}\n${analyticsClient}`, { ecma: 2020, compress: { passes: 2 }, mangle: true, format: { comments: false } });
  if (!compiled.code) throw new Error('Archive motion produced no output');
  const body = `${compiled.code}\n`;
  const hash = createHash('sha256').update(body).digest('hex').slice(0, 12);
  return { thumbs, fontFaces, motionScript: { path: `js/archive.${hash}.min.js`, body } };
}

async function writeIfChanged(file, body) {
  try { if (await readFile(file, 'utf8') === body) return; } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, body);
}

export async function generateMediaArchive({ root = projectRoot, manifest, siteRoot = path.join(root, 'preview_site') } = {}) {
  manifest ||= JSON.parse(await readFile(path.join(siteRoot, 'assets/gallery-manifest.json'), 'utf8'));
  // Derive the allowlist from this manifest before compiling either client.
  // The imported route module still describes the preceding build until the
  // file below is written, and ESM keeps that previous value in memory.
  const analyticsClient = createAnalyticsClient(buildMediaArchive(manifest).pages);
  const result = buildMediaArchive(manifest, await archiveAssets(siteRoot, analyticsClient));
  // Remove only our generated HTML when collections shrink; never authored files.
  let entries = [];
  try { entries = await readdir(path.join(siteRoot, 'archive'), { recursive: true }); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  for (const entry of entries.filter(name => name.endsWith('.html'))) {
    const relative = `archive/${entry}`;
    if (!result.files.has(relative) && (await readFile(path.join(siteRoot, relative), 'utf8')).includes(GENERATED)) await rm(path.join(siteRoot, relative));
  }
  for (const [relative, body] of result.files) await writeIfChanged(path.join(siteRoot, relative), body);
  await writeIfChanged(path.join(root, 'functions/_media-archive-routes.js'), result.routeModule);
  console.log(`Media archive: ${result.pages.length} index pages linking ${result.imageCount} unique images and ${result.videoCount} videos to canonical works.`);
  return { ...result, analyticsClient };
}

