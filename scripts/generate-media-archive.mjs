function normalizeManifest(manifest) {
  if (!Array.isArray(manifest?.images) || !Array.isArray(manifest?.videos)) throw new Error('Invalid gallery manifest');
  const seen = new Set();
  return [...manifest.images.map(record => ({ ...record, type: 'image' })), ...manifest.videos.map(record => ({ ...record, type: 'video' }))].map(record => {
    if (!/^[A-Za-z]+\/[A-Za-z][A-Za-z0-9_-]*\.(?:webp|mp4)$/.test(record.path || '') || seen.has(record.path)) throw new Error(`Invalid or duplicate media path: ${record.path}`);
    seen.add(record.path);
    const [folder, filename] = record.path.split('/');
    const collection = COLLECTIONS[folder];
    if (!collection || (record.type === 'video') !== filename.endsWith('.mp4') || (record.type === 'video') !== (folder === 'Videos')) throw new Error(`Unknown media collection: ${record.path}`);
    if (![record.width, record.height].every(n => Number.isInteger(n) && n > 0)) throw new Error(`Missing media dimensions: ${record.path}`);
    const stem = filename.replace(/\.[^.]+$/, '');
    const numbered = stem.match(/^[A-Za-z]+([1-9]\d*)$/);
    const number = numbered ? Number(numbered[1]) : Number.MAX_SAFE_INTEGER;
    return { ...record, folder, slug: collection[0], collection: collection[1], stem, number,
      title: numbered ? `${collection[2]} ${String(number).padStart(2, '0')}` : `${collection[2]} — ${stem}`, url: originalURL(record.path) };
  });
}

function pagination(slug, current, count) {
  if (count < 2) return '';
  let links = current > 1 ? `<a rel="prev" href="${pageURL(slug, current - 1)}">Previous</a>` : '';
  for (let page = 1; page <= count; page++) links += page === current
    ? `<span aria-current="page" aria-label="Page ${page}">${page}</span>`
    : `<a href="${pageURL(slug, page)}" aria-label="Page ${page}">${page}</a>`;
  if (current < count) links += `<a rel="next" href="${pageURL(slug, current + 1)}">Next</a>`;
  return `<nav class="pagination" aria-label="Archive pages">${links}</nav>`;
}

function card(item, index, posters) {
  const watch = item.type === 'video' && posters.has(item.path);
  const href = watch ? videoURL(item) : item.url;
  const source = item.type === 'image' ? item.url : watch ? posterURL(item) : null;
  const image = source ? `<a class="media" href="${escape(href)}" tabindex="-1" aria-hidden="true"><img src="${escape(source)}" alt="${escape(item.title)}" width="${item.width}" height="${item.height}" loading="${index < 2 ? 'eager' : 'lazy'}" decoding="async"></a>` : '';
  return `<article class="card" id="${item.stem.toLowerCase()}">${image}<div class="caption"><h2><a href="${escape(href)}">${escape(item.title)}${watch ? ' · Watch' : ''}</a></h2><p>${escape(item.collection)} · Barakat Qurtas portfolio</p></div></article>`;
}

const urlset = (entries, namespace = '') => `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"${namespace}>\n${entries.join('\n')}\n</urlset>\n`;
const imageEntry = (route, images) => `  <url><loc>${escape(SITE + route)}</loc>${images.map(url => `\n    <image:image><image:loc>${escape(url)}</image:loc></image:image>`).join('')}\n  </url>`;

export function buildMediaArchive(manifest, { pageSize = 24, posters = new Set(), siteImages = [] } = {}) {
  if (!Number.isInteger(pageSize) || pageSize < 1 || pageSize > 100) throw new Error('Invalid archive page size');
  const items = normalizeManifest(manifest), files = new Map(), pages = [], images = [], videos = [];
  const addPage = (route, values) => {
    files.set(`${route.slice(1)}index.html`, documentHTML({ ...values, route }));
    pages.push(route);
  };
  const categories = [];
  for (const [folder, [slug, label]] of Object.entries(COLLECTIONS)) {
    const collection = items.filter(item => item.folder === folder).sort((a, b) => a.number - b.number);
    if (!collection.length) continue;
    categories.push(`<div class="card"><a class="category-link" href="${pageURL(slug)}">${escape(label)}<span>${collection.length} ${folder === 'Videos' ? 'videos' : 'images'} ↗</span></a></div>`);
    const totalPages = Math.ceil(collection.length / pageSize);
    for (let page = 1; page <= totalPages; page++) {
      const batch = collection.slice((page - 1) * pageSize, page * pageSize);
      const route = pageURL(slug, page);
      const title = `${label} — Archive${totalPages > 1 ? `, page ${page}` : ''}`;
      const range = `${(page - 1) * pageSize + 1}–${Math.min(page * pageSize, collection.length)}`;
      const description = `${label} from Barakat Qurtas’s portfolio. Browse works ${range} of ${collection.length}.`;
      const navigation = pagination(slug, page, totalPages);
      addPage(route, { title, description, image: batch[0].type === 'image' ? batch[0].url : posters.has(batch[0].path) ? SITE + posterURL(batch[0]) : null,
        content: `<p class="crumb"><a href="/archive/">Archive</a> / ${escape(label)}</p><section class="intro"><p class="eyebrow">Works ${range} / ${collection.length}</p><h1>${escape(label)}</h1><p>${folder === 'Videos' ? 'Films and motion work from the portfolio. Choose a video to watch.' : 'Original images from the portfolio. Select a work to view it at its original size.'}</p></section>${navigation}<div class="grid">${batch.map((item, index) => card(item, index, posters)).join('\n')}</div>${navigation}` });
      const originalImages = batch.filter(item => item.type === 'image').map(item => item.url);
      if (originalImages.length) images.push(imageEntry(route, originalImages));
    }
  }

  const watchable = items.filter(item => item.type === 'video' && posters.has(item.path));
  watchable.forEach((item, index) => {
    const route = videoURL(item), thumbnail = SITE + posterURL(item);
    const description = `${item.title} from Barakat Qurtas’s video portfolio. Watch the complete video.`;
    const adjacent = [watchable[index - 1], watchable[index + 1]].filter(Boolean);
    addPage(route, { title: item.title, description, image: thumbnail,
      content: `<p class="crumb"><a href="/archive/">Archive</a> / <a href="/archive/videos/">Videos</a></p><section class="watch-intro"><p class="eyebrow">Video portfolio</p><h1>${escape(item.title)}</h1></section><div class="player"><video controls playsinline preload="metadata" src="${escape(item.url)}" poster="${posterURL(item)}" width="${item.width}" height="${item.height}" aria-label="${escape(item.title)}"><a href="${escape(item.url)}">Open ${escape(item.title)}</a></video></div><p class="details">${escape(description)}</p><p><a href="${escape(item.url)}">Open original video</a></p><nav class="pagination" aria-label="More videos">${adjacent.map(other => `<a href="${videoURL(other)}">${escape(other.title)}</a>`).join('')}<a href="/archive/videos/">All videos</a></nav>` });
    // Dates are intentionally absent: the catalogue does not record when a
    // video was first published. A video sitemap does not require that field.
    videos.push(`  <url><loc>${SITE}${route}</loc><video:video><video:thumbnail_loc>${thumbnail}</video:thumbnail_loc><video:title>${escape(item.title)}</video:title><video:description>${escape(description)}</video:description><video:content_loc>${escape(item.url)}</video:content_loc></video:video></url>`);
  });
  addPage('/archive/', { title: 'Work Archive', description: `Browse ${manifest.images.length} images and ${manifest.videos.length} videos from Barakat Qurtas’s design portfolio.`,
    content: `<section class="intro"><p class="eyebrow">The complete collection</p><h1>Work archive.</h1><p>${manifest.images.length} images and ${manifest.videos.length} videos, organised by discipline. Explore the collection, view original artwork and watch films.</p></section><div class="grid">${categories.join('\n')}</div>` });
  for (const group of siteImages) {
    if (!/^\/(?:bio|blog|contact)?$/.test(group.page) || !Array.isArray(group.images) || !group.images.every(url => /^https:\/\//.test(url))) throw new Error('Invalid supplementary image sitemap');
    images.unshift(imageEntry(group.page, group.images));
  }
  files.set('sitemap-images.xml', urlset(images, ' xmlns:image="http://www.google.com/schemas/sitemap-image/1.1"'));
  files.set('sitemap-videos.xml', urlset(videos, ' xmlns:video="http://www.google.com/schemas/sitemap-video/1.1"'));
  files.set('sitemap-gallery.xml', urlset(pages.map(route => `  <url><loc>${SITE}${route}</loc></url>`)));
  const routeModule = `// Generated by scripts/generate-media-archive.mjs; do not edit.\nexport const MEDIA_ARCHIVE_ROUTES = new Set(${JSON.stringify([...pages].sort(), null, 2)});\n`;
  return { files, pages, routeModule, imageCount: manifest.images.length, videoCount: videos.length,
    missingPosters: items.filter(item => item.type === 'video' && !posters.has(item.path)).map(item => item.path) };
}

// Validate that a committed poster is a real, sufficiently sized JPEG before
// advertising it to search engines. Missing posters never create watch URLs.
export function jpegDimensions(bytes) {
  if (bytes.length < 4 || bytes.readUInt16BE(0) !== 0xffd8) throw new Error('Invalid JPEG poster');
  let offset = 2;
  while (offset + 4 <= bytes.length) {
    if (bytes[offset++] !== 0xff) throw new Error('Invalid JPEG marker');
    while (bytes[offset] === 0xff) offset++;
    const marker = bytes[offset++];
    if (marker === 0xda || marker === 0xd9) break;
    const length = bytes.readUInt16BE(offset);
    if (length < 2 || offset + length > bytes.length) break;
    if ([0xc0, 0xc1, 0xc2].includes(marker) && length >= 7) return { width: bytes.readUInt16BE(offset + 5), height: bytes.readUInt16BE(offset + 3) };
    offset += length;
  }
  throw new Error('JPEG poster has no dimensions');
}

async function writeIfChanged(file, body) {
  try { if (await readFile(file, 'utf8') === body) return; } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, body);
}

export async function generateMediaArchive({ root = projectRoot, manifest, siteRoot = path.join(root, 'preview_site') } = {}) {
  manifest ||= JSON.parse(await readFile(path.join(siteRoot, 'assets/gallery-manifest.json'), 'utf8'));
  const items = normalizeManifest(manifest), posters = new Set();
  for (const item of items.filter(item => item.type === 'video')) {
    try {
      const dimensions = jpegDimensions(await readFile(path.join(siteRoot, posterURL(item))));
      if (dimensions.width < 60 || dimensions.height < 30) throw new Error(`Poster too small: ${item.path}`);
      posters.add(item.path);
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  const siteImages = JSON.parse(await readFile(path.join(root, 'scripts/site-images.json'), 'utf8'));
  const result = buildMediaArchive(manifest, { posters, siteImages });
  // Remove only our own generated HTML if a collection shrinks or disappears.
  for (const base of ['archive', 'watch']) {
    let entries;
    try { entries = await readdir(path.join(siteRoot, base), { recursive: true }); } catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    for (const entry of entries.filter(name => name.endsWith('.html'))) {
      const relative = `${base}/${entry}`;
      if (!result.files.has(relative) && (await readFile(path.join(siteRoot, relative), 'utf8')).includes(GENERATED)) await rm(path.join(siteRoot, relative));
    }
  }
  for (const [relative, body] of result.files) await writeIfChanged(path.join(siteRoot, relative), body);
  await writeIfChanged(path.join(root, 'functions/_media-archive-routes.js'), result.routeModule);
  console.log(`Media archive: ${result.pages.length} pages, ${result.imageCount} images, ${result.videoCount} watch pages.`);
  if (result.missingPosters.length) console.warn(`Watch pages omitted until real posters are supplied: ${result.missingPosters.join(', ')}`);
  return result;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await generateMediaArchive();
